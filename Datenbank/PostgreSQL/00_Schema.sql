CREATE TABLE IF NOT EXISTS "Zustandsdaten" (
    "Id"                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Timestamp"         TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "MaschinenId"       BIGINT NOT NULL,
    "ZustandsmeldungId" BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS "Stoerungsdaten" (
    "Id"                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Timestamp"          TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "MaschinenId"        BIGINT NOT NULL,
    "StoerungsmeldungId" BIGINT NOT NULL
);

-- ── Produktionsplanung ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "Planungs" (
    "Id"            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Datum"         TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "MaschinenId"   BIGINT       NOT NULL,
    "Personalsoll"  INTEGER      NULL,
    "Personalnamen" VARCHAR(500) NULL,
    "Artikel"       VARCHAR(100) NULL,
    "Sollmenge"     INTEGER      NULL,
    "MHD"           TIMESTAMP WITHOUT TIME ZONE NULL,
    "Kartonsanzahl" VARCHAR(100) NULL,
    "PersonalIst"   INTEGER      NULL,
    "Fertigware"    INTEGER      NULL,
    "Starten"       INTERVAL     NULL,
    "Stoppen"       INTERVAL     NULL,
    "Pause"         INTEGER      NULL
);

