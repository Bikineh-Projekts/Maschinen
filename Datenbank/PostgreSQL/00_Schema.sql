-- ── Stammdaten ──────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "maschinen" (
    "Id"          BIGINT       PRIMARY KEY,
    "Bezeichnung" VARCHAR(200) NOT NULL,
    "IpAdresse"   VARCHAR(50)  NULL
);

CREATE TABLE IF NOT EXISTS "Zustandsmeldung" (
    "Id"      BIGINT       PRIMARY KEY,
    "Meldung" VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS "Stoerungsmeldung" (
    "Id"      BIGINT       PRIMARY KEY,
    "Meldung" VARCHAR(500) NOT NULL
);

-- ── Messdaten (werden von der OPC-Anbindung geschrieben) ─────────────────────
CREATE TABLE IF NOT EXISTS "Leistungsdaten" (
    "Id"               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Timestamp"        TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "MaschinenId"      BIGINT  NOT NULL,
    "PRnummer"         INTEGER NOT NULL,
    "Tagestaktzaehler" INTEGER NOT NULL,
    "Packungszaeler"   INTEGER NOT NULL,
    "Maschinentakte"   INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS "Abzugsdaten" (
    "Id"                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Timestamp"         TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "MaschinenId"       BIGINT  NOT NULL,
    "PRnummer"          INTEGER NOT NULL,
    "PackungenproAbzug" BIGINT  NOT NULL,
    "Abzuglaenge"       BIGINT  NOT NULL
);

CREATE TABLE IF NOT EXISTS "Temperaturdaten" (
